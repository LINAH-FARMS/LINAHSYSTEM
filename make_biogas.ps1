function B { param($t,$i) $sel.Font.Size=11; $sel.Font.Bold=$false; $sel.Font.Name='Arial'; $sel.Font.Color=0; if($i){$sel.ParagraphFormat.LeftIndent=$i}; $sel.TypeText("  $t"); $sel.TypeParagraph(); $sel.ParagraphFormat.LeftIndent=0 }

function T { param($h,$r)
  $tbl = $doc.Tables.Add($sel.Range, $r.Count+1, $h.Count)
  $tbl.Borders.Enable = 1
  for($c=0;$c -lt $h.Count;$c++){ $c2=$tbl.Cell(1,$c+1); $c2.Range.Font.Size=10; $c2.Range.Font.Bold=$true; $c2.Range.Font.Name='Arial'; $c2.Range.Text=$h[$c]; $c2.Shading.BackgroundPatternColor=57; $c2.Range.Font.Color=16777215 }
  for($i=0;$i -lt $r.Count;$i++){ for($c=0;$c -lt $r[$i].Count;$c++){ $c2=$tbl.Cell($i+2,$c+1); $c2.Range.Font.Size=10; $c2.Range.Font.Name='Arial'; $c2.Range.Font.Color=0; $c2.Range.Text=$r[$i][$c] } }
  $sel.EndKey(6); $sel.TypeParagraph()
}

